-- ============================================================================
-- Echo Barrier Hub — Suppliers + Item Catalogue (SRO slice 2)
-- Target project: korylyniwsqtsvzuzydg ("Hubspot Shipping and Stocks") — SHARED.
--
-- PURELY ADDITIVE — two NEW tables only. Touches nothing the live n8n PO Phase 1/2
-- or the snapshot pipelines read or write, so those are unaffected by construction.
--
-- What this adds (both follow the existing po_* picklist pattern: read-all for
-- authenticated, writes via service-role only; seeded here, edited later via UI):
--
--   1. po_suppliers   — the supplier/vendor register (picklist source for supplier
--      & BOM POs). Seeded verbatim from Unleashed "Supplier List" (23/06/2026, 32
--      rows). Overhead vendors (Adobe / Edenred / Slovak Telekom / Stock Journal)
--      and duplicate shadows (BAM, HEND, INVC Ltd) are seeded active = false so the
--      picklist is clean while nothing is lost. Bamida carries its full address +
--      VAT (used by the Bamida supplier-PO doc, which now reads this table).
--
--   2. item_catalog   — the full Unleashed item master (317 rows from the
--      "Product List", 23/06/2026): finished barriers, Bamida manufacturing,
--      printing, raw materials, packaging, services. The picklist source for the
--      BOM / supplier-PO side (slice 3) and the real codes behind the Bamida PO.
--      Normalisations from the PDF: stock-qty columns dropped; a trailing column-
--      artifact dash stripped from codes (`1244 -` → `1244`); six back-to-back
--      wrapped descriptions hand-corrected. currency defaults to EUR (SRO).
--
-- Distinct from the existing tables (left UNTOUCHED): po_product_catalog = the
-- depot-orderable finished-goods picklist (14 NA SKUs); product_code_master =
-- the per-entity Xero code cross-reference. item_catalog is the SRO/supplier-side
-- item universe, a separate namespace.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1. po_suppliers
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.po_suppliers (
  id              uuid PRIMARY KEY DEFAULT uuid_generate_v4(),
  code            text NOT NULL UNIQUE,
  name            text NOT NULL,
  city            text,
  country         text,
  currency        text,
  address         text,           -- full multiline address (only some known, e.g. Bamida)
  tax_number      text,           -- VAT / IČ DPH where known
  xero_contact_id text,           -- hardcoded into the n8n Xero flow once fetched
  active          boolean NOT NULL DEFAULT true,
  created_at      timestamptz NOT NULL DEFAULT now()
);

