-- ----------------------------------------------------------------------------
-- 3. RLS — picklist pattern (read-all authenticated; writes service-role only)
-- ----------------------------------------------------------------------------
ALTER TABLE public.po_suppliers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.item_catalog ENABLE ROW LEVEL SECURITY;

DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['po_suppliers','item_catalog']
  LOOP
    EXECUTE format('REVOKE ALL ON public.%I FROM anon', t);
    EXECUTE format('REVOKE INSERT, UPDATE, DELETE ON public.%I FROM authenticated', t);
    EXECUTE format('GRANT SELECT ON public.%I TO authenticated', t);
    EXECUTE format('DROP POLICY IF EXISTS "picklist readable by authenticated" ON public.%I', t);
    EXECUTE format(
      'CREATE POLICY "picklist readable by authenticated" ON public.%I FOR SELECT TO authenticated USING (true)', t);
  END LOOP;
END$$;
